# ------------------------------------------------------------------
# Helper: fit and evaluate one gene set
# ------------------------------------------------------------------

eval_gene_set <- function(genes, verbose = FALSE) {
  x_tr <- tcga_df[, genes, drop = FALSE]
  y_tr <- factor(
    ifelse(tcga_df$condition == "Primary Tumor", "Tumor", "Normal"),
    levels = c("Normal", "Tumor")
  )

  rf_mod <- train(
    x = x_tr,
    y = y_tr,
    method = "rf",
    metric = "ROC",
    trControl = ctrl_pan,
    tuneLength = tune_len
  )

  aucs <- purrr::map_dbl(names(ext_sets), function(nm) {
    s <- ext_sets[[nm]]
    X <- s$expr[, genes, drop = FALSE]
    X[] <- lapply(X, as.numeric)

    probs <- predict(rf_mod, newdata = X, type = "prob")[, "Tumor"]
    roc_obj <- pROC::roc(s$truth, probs, quiet = TRUE)
    a <- as.numeric(pROC::auc(roc_obj))

    if (verbose) {
      message("  ", nm, " AUC = ", sprintf("%.3f", a))
    }

    a
  })

  mean(aucs)
}

