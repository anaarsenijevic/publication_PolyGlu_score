message("Fetching Ensembl to gene symbol mapping via biomaRt...")
ensembl <- useMart("ensembl", dataset = "hsapiens_gene_ensembl")

gene_map <- getBM(
  attributes = c("ensembl_gene_id", "external_gene_name"),
  mart = ensembl
) %>%
  filter(external_gene_name != "") %>%
  distinct(ensembl_gene_id, .keep_all = TRUE)

# ------------------------------------------------------------------
# Load and VST-normalize TCGA matched cohorts
# ------------------------------------------------------------------

message("Loading TCGA matched DESeq2 objects...")
dds_files <- list.files(
  tcga_dir,
  pattern = "dds_.*_matched_group\\.rds$",
  full.names = TRUE
)

if (length(dds_files) == 0) {
  stop("No TCGA DESeq2 files found in 'tcga_dir'.")
}

tcga_list <- list()

for (f in dds_files) {
  proj <- sub("dds_(.*)_matched_group\\.rds", "\\1", basename(f))
  dds <- readRDS(f)
  vsd <- vst(dds, blind = TRUE)
  mat <- assay(vsd)

  ens <- sub("\\..*", "", rownames(mat))
  syms <- gene_map$external_gene_name[match(ens, gene_map$ensembl_gene_id)]

  keep <- !is.na(syms) & syms != ""
  mat <- mat[keep, , drop = FALSE]
  rownames(mat) <- syms[keep]

  expr <- as.data.frame(t(mat))
  expr$sample <- rownames(expr)
  expr$condition <- as.character(colData(dds)[expr$sample, "condition"])
  expr$project <- proj

  tcga_list[[proj]] <- expr
}

tcga_df <- bind_rows(tcga_list) %>%
  filter(!is.na(condition)) %>%
  relocate(sample, condition, project)

tcga_labels <- factor(
  ifelse(tcga_df$condition == "Primary Tumor", "Tumor", "Normal"),
  levels = c("Normal", "Tumor")
)

gene_universe_tcga <- setdiff(colnames(tcga_df), c("sample", "condition", "project"))

